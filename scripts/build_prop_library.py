"""Export the parametric defaults as portable GLB and editable Blender assets."""
import hashlib
import json
import sys
from pathlib import Path
import bpy
sys.path.insert(0,str(Path(__file__).resolve().parent))
from scene_plan import validate_scene,object_catalog
from scene_objects import SceneObjects
from duel_plan import PROJECT,atomic_json


def main():
    folder=PROJECT/'assets/props/generated';folder.mkdir(parents=True,exist_ok=True);manifest=[]
    for kind,definition in object_catalog()['objects'].items():
        bpy.ops.wm.read_factory_settings(use_empty=True)
        bpy.context.preferences.filepaths.save_version=0
        plan=validate_scene({'version':1,'duration_seconds':1,'objects':[{'id':kind,'type':kind,'position':[0,0,0]}]},'asset_'+kind)
        props=SceneObjects(plan)
        for obj in props.collection.objects: obj.select_set(True)
        path=folder/(kind+'.glb')
        bpy.ops.export_scene.gltf(filepath=str(path),export_format='GLB',use_selection=True,export_extras=True)
        bpy.ops.wm.save_as_mainfile(filepath=str(folder/(kind+'.blend')))
        manifest.append({'id':kind,'provider':'project_procedural','size':definition['size'],'glb':str(path.relative_to(PROJECT)),
                         'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'blend':str((folder/(kind+'.blend')).relative_to(PROJECT)),
                         'anchors':definition['anchors'],'anchor_nodes':{name:obj.name for name,obj in props.objects[kind]['anchors'].items()},
                         'actions':definition['actions']})
    atomic_json(folder/'manifest.json',{'version':1,'assets':manifest,'generator':'scripts/scene_objects.py',
                'generator_sha256':hashlib.sha256((PROJECT/'scripts/scene_objects.py').read_bytes()).hexdigest(),
                'origin':'Parametric models generated by this project; no third-party furniture assets used.'})
    print('PROP_LIBRARY_READY',len(manifest),flush=True)


if __name__=='__main__': main()
